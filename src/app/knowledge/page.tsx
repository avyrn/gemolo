function AccordionItem({ article, idx }: { article: Article; idx: number }) {
  const [open, setOpen] = useState(idx === 0);
  return (
    <div className="accordion-item">
      <button className="accordion-header" onClick={() => setOpen(!open)}>
        <span>{article.title}</span>
        {open ? <ChevronUp size={18} color="var(--color-primary)" /> : <ChevronDown size={18} color="var(--color-text-muted)" />}
      </button>
      {open && (
        <div className="accordion-body">
          {article.content.split('\n').map((line, i) => {
            const trimmed = line.trim();
            if (!trimmed) return <div key={i} style={{ marginTop: 8 }} />;
            if (trimmed.startsWith('**') && trimmed.endsWith('**')) {
              return <div key={i} style={{ fontWeight: 700, color: 'var(--color-text)', marginTop: 12, marginBottom: 4 }}>{trimmed.replace(/\*\*/g, '')}</div>;
            }
            if (trimmed.startsWith('•')) {
              return <div key={i} style={{ paddingLeft: 16, marginBottom: 4 }}>{trimmed}</div>;
            }
            // inline bold
            const parts = trimmed.split(/(\*\*[^*]+\*\*)/g);
            return (
              <div key={i} style={{ marginBottom: 4 }}>
                {parts.map((p, j) =>
                  p.startsWith('**') ? <strong key={j}>{p.replace(/\*\*/g, '')}</strong> : <span key={j}>{p}</span>
                )}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}

